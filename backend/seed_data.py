"""
Database initialisation + seed data (80+ clothing items)
"""
from __future__ import annotations

import json
from datetime import datetime, timedelta

from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker, Session

from models import Base, Product, ReviewPhoto, FlaggedSeller

DATABASE_URL = "sqlite:///./fashion.db"

engine         = create_engine(DATABASE_URL, connect_args={"check_same_thread": False})
SessionLocal   = sessionmaker(bind=engine, autoflush=False, autocommit=False)


def get_db():
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()


def init_db():
    Base.metadata.create_all(bind=engine)


def seed_db():
    db: Session = SessionLocal()
    try:
        if db.query(Product).count() > 0:
            return  # already seeded
        items = _build_seed_items()
        for data in items:
            p = Product(**{k: v for k, v in data.items() if hasattr(Product, k)})
            db.add(p)
        db.commit()

        # Add a few sample review photos for product 1
        for url in [
            "https://images.unsplash.com/photo-1521572163474-6864f9cf17ab?w=400",
            "https://images.unsplash.com/photo-1503341504253-dff4815485f1?w=400",
        ]:
            rp = ReviewPhoto(
                product_id=1,
                image_url=url,
                phash_string="a3c5e7f9b1d2e4f6",
                camera_model="iPhone 14 Pro",
                software_used=None,
                is_suspicious=False,
                is_duplicate=False,
                hamming_distance=18,
            )
            db.add(rp)
        db.commit()
        print(f"[SUCCESS] Seeded {len(items)} products")
    finally:
        db.close()


